"""Turns data/measurements.json (from plugin/BuildReplayMeasure.cs) into src/js/measured.js.

Usage: python3 tools/import_measurements.py

Every placeable item becomes one catalog row with its exact bounds and collision boxes, converted
from Rust's (Unity, left-handed) local space to the sandbox's (three.js, right-handed) local space.
Items that mount in a wall opening are turned so their width runs along the wall like the sandbox's walls.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "measurements.json")
OUT = os.path.join(ROOT, "src", "js", "measured.js")

# Keep the ids the sandbox already used for these, so older builds and the example bases still load.
ID_ALIAS = {"cupboard.tool": "cupboard.tool.deployed", "sleepingbag": "sleepingbag_leather_deployed"}
CATEGORY = {"Weapon": "Siege", "Resources": "Electrical"}
SKIP_CATEGORIES = {"Ammunition"}
MAX_PARTS = 14


def place_of(prefab, item):
    p = prefab.lower()
    if p.startswith("door.hinged"):
        return "doorway"
    if p.startswith("door.double.hinged") or p.startswith("wall.frame."):
        return "frame"
    if p.startswith("wall.window.") or p.startswith("shutter."):
        return "window"
    if p.startswith("floor.triangle.") and ("hatch" in p or "grill" in p):
        return "hatch.tri"
    if p.startswith("floor.") and ("hatch" in p or "grill" in p):
        return "hatch"
    return "free"


def r(v):
    return round(v, 3)


def convert(box, place):
    (cx, cy, cz), (sx, sy, sz) = box["center"], box["size"]
    if place in ("doorway", "frame", "window"):
        # Rust doors face along x (width along z); sandbox walls run along x.
        return [r(cz), r(cy), r(cx), r(sz), r(sy), r(sx)]
    return [r(cx), r(cy), r(-cz), r(sx), r(sy), r(sz)]


def main():
    data = json.load(open(SRC))
    rows, seen = [], set()
    for e in data["deployables"]:
        item = e["item"]
        if item.startswith(("seed.", "clone.")) or e["category"] in SKIP_CATEGORIES or not e.get("bounds"):
            continue
        sid = ID_ALIAS.get(item, item)
        if sid in seen:
            continue
        seen.add(sid)
        place = place_of(e["prefab"], item)
        bounds = convert(e["bounds"], place)
        parts = []
        for c in e.get("colliders") or []:
            name = (c.get("name") or "").lower()
            if "prevent" in name or "trigger" in name:
                continue
            b = convert(c, place)
            if max(b[3:]) < 0.02:
                continue
            if b not in parts:
                parts.append(b)
        parts.sort(key=lambda b: -(b[3] * b[4] * b[5]))
        parts = parts[:MAX_PARTS]
        rows.append([sid, e["name"], CATEGORY.get(e["category"], e["category"]), place, bounds, parts])
    rows.sort(key=lambda row: (row[2], row[1].lower()))
    meta = {"rustVersion": data.get("rustVersion"), "measuredAt": data.get("measuredAt"), "items": len(rows)}
    with open(OUT, "w") as f:
        f.write("// Generated by tools/import_measurements.py from data/measurements.json. Do not edit by hand.\n")
        f.write("// Each row: [id, name, category, mount, bounds, collision boxes]; boxes are [cx, cy, cz, sx, sy, sz] in metres.\n")
        f.write("const MEASURED_META = " + json.dumps(meta) + ";\n")
        f.write("const MEASURED = [\n")
        f.write(",\n".join(json.dumps(row, separators=(",", ":")) for row in rows))
        f.write("\n];\n")
    print("Wrote", len(rows), "items to", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
